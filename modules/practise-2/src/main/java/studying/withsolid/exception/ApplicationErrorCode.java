package studying.withsolid.exception;

/**
 * Коды прикладных ошибок сервиса отчётов.
 * <p>
 * Используются в связке с {@link ApplicationException}, чтобы вызывающий
 * код мог обрабатывать ошибки программно (по коду), не полагаясь на
 * текст сообщения об ошибке, который предназначен для человека.
 */
public enum ApplicationErrorCode {

    /**
     * Некорректные входные данные: отчёт или email не переданы
     * ({@code null}/пусты), либо числовые показатели отчёта отрицательны.
     */
    VALIDATION_ERROR,

    /**
     * Ошибка записи отчёта в файл. Как правило, оборачивает исходное
     * исключение ввода-вывода ({@code IOException}), сохранённое как
     * {@linkplain ApplicationException#getCause() причина}.
     */
    FILE_WRITE_ERROR
}